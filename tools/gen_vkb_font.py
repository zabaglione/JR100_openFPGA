ORDER = [chr(ord("A") + i) for i in range(26)] + \
        [chr(ord("0") + i) for i in range(10)] + \
        [";", ",", ".", ":", "-"]


def row_bits(pattern: str) -> int:
    assert len(pattern) == 8, f"bad row width: {pattern!r}"
    value = 0
    for i, ch in enumerate(pattern):
        assert ch in "#.", f"bad char in {pattern!r}"
        if ch == "#":
            value |= 0x80 >> i
    return value


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "src/fpga/core/jr100_vkb_font.sv"
    lines: list[str] = []
    lines.append("// GENERATED FILE - edit tools/gen_vkb_font.py and re-run it instead.")
    lines.append("//")
    lines.append("// 8x8 glyphs for the virtual keyboard labels. Label codes:")
    lines.append("// 0 blank, 1-26 A-Z, 27-36 digits 0-9, 37 ';' 38 ',' 39 '.' 40 ':' 41 '-'.")
    lines.append("//")
    lines.append("// SPDX-License-Identifier: GPL-2.0-or-later")
    lines.append("")
    lines.append("`default_nettype none")
    lines.append("")
    lines.append("module jr100_vkb_font (")
    lines.append("    input  wire [5:0] code,")
    lines.append("    input  wire [2:0] row,")
    lines.append("    output reg  [7:0] bits")
    lines.append(");")
    lines.append("")
    lines.append("always @(*) begin")
    lines.append("    case ({code, row})")
    for idx, ch in enumerate(ORDER, start=1):
        rows = GLYPHS[ch]
        assert len(rows) == 7, f"glyph {ch!r} must have 7 rows"
        for r, pattern in enumerate(rows):
            v = row_bits(pattern)
            if v:
                label = ch if ch not in ";," else f"'{ch}'"
                lines.append(
                    f"        {{6'd{idx}, 3'd{r}}}: bits = 8'h{v:02X};  // {label}"
                )
    lines.append("        default: bits = 8'h00;")
    lines.append("    endcase")
    lines.append("end")
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    lines.append("`default_nettype wire")
    lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(ORDER)} glyphs)")

    # Self-check render: print every glyph back as ASCII art.
    for ch in ORDER:
        rendered = ["".join("#" if row_bits(p) & (0x80 >> i) else "."
                            for i in range(8))
                    for p in GLYPHS[ch]]
        assert rendered == GLYPHS[ch], f"round-trip failed for {ch!r}"
    print("glyph round-trip check passed")


if __name__ == "__main__":
    main()
